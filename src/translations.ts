export function getPioneerTier(accountNumber: number) {
  if (accountNumber === 1) return 'first_ever';
  if (accountNumber <= 10) return 'top_10';
  if (accountNumber <= 100) return 'top_100';
  if (accountNumber <= 1000) return 'top_1000';
  if (accountNumber <= 10000) return 'top_10000';
  return 'member';
}

